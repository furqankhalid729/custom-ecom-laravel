<?php

namespace Custom\GoogleMerchant\Support;

use Webkul\Core\Repositories\ChannelRepository;

/**
 * Store facts Google needs: public website URL and policy page URLs.
 */
class StoreSettings
{
    public function __construct(
        protected Settings $settings,
        protected ChannelRepository $channelRepository,
    ) {}

    public function websiteUrl(int $channelId): string
    {
        $configured = trim((string) $this->settings->get('store.website_url'));

        if ($configured !== '') {
            return rtrim($configured, '/');
        }

        $channel = $this->channelRepository->find($channelId);

        if ($channel?->hostname) {
            $host = $channel->hostname;

            return rtrim(str_contains($host, '://') ? $host : 'https://'.$host, '/');
        }

        return rtrim((string) config('app.url'), '/');
    }

    /**
     * @return array{return: ?string, refund: ?string, terms: ?string, privacy: ?string}
     */
    public function policyUrls(int $channelId): array
    {
        $generated = $this->generatedPolicyUrls($channelId);

        $urls = [];

        foreach (['return' => 'return_policy_url', 'refund' => 'refund_policy_url', 'terms' => 'terms_url', 'privacy' => 'privacy_url'] as $key => $field) {
            $configured = trim((string) $this->settings->get('store.'.$field));

            $urls[$key] = $configured !== '' ? $configured : ($generated[$key] ?? null);
        }

        return $urls;
    }

    /**
     * True only for https URLs on a public host (not localhost, *.test, *.local or a private/reserved IP).
     */
    public function isPublicHttps(?string $url): bool
    {
        $parts = parse_url((string) $url);

        if (($parts['scheme'] ?? null) !== 'https' || empty($parts['host'])) {
            return false;
        }

        $host = strtolower(trim($parts['host'], '[]'));

        if ($host === 'localhost' || str_ends_with($host, '.localhost') || str_ends_with($host, '.test') || str_ends_with($host, '.local') || ! str_contains($host, '.') && ! filter_var($host, FILTER_VALIDATE_IP)) {
            return false;
        }

        if (filter_var($host, FILTER_VALIDATE_IP)) {
            return (bool) filter_var($host, FILTER_VALIDATE_IP, FILTER_FLAG_NO_PRIV_RANGE | FILTER_FLAG_NO_RES_RANGE);
        }

        return true;
    }

    /**
     * URLs of pages generated by the Store Policies package, when it is installed.
     */
    protected function generatedPolicyUrls(int $channelId): array
    {
        $service = 'Custom\StorePolicy\Services\PolicyStatusService';

        if (! class_exists($service)) {
            return [];
        }

        $map = ['return' => 'return-policy', 'refund' => 'refund-policy', 'terms' => 'terms-conditions', 'privacy' => 'privacy-policy'];

        try {
            $statuses = app($service)->forChannel($channelId);
        } catch (\Throwable) {
            return [];
        }

        $base = $this->websiteUrl($channelId);

        $urls = [];

        foreach ($map as $key => $template) {
            $urlKey = $statuses[$template]['url_key'] ?? null;

            if ($urlKey && ! empty($statuses[$template]['page_id'])) {
                $urls[$key] = $base.'/page/'.$urlKey;
            }
        }

        return $urls;
    }
}
